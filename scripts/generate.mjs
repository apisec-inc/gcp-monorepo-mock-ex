#!/usr/bin/env node
// Generates every service, firestore.rules, indexes, firebase.json, OpenAPI specs
// and a function manifest from config/domains.json.
//   --limit N         only N resources per domain (fast local builds)
//   --with-findings   apply config/findings.json (deliberate weaknesses)
//   --project / --region  used for API Gateway backend URLs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);
const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };

const cfg = JSON.parse(fs.readFileSync(path.join(root, "config/domains.json"), "utf8"));
const limit = Number(opt("limit", 0)) || Infinity;
const project = opt("project", cfg.project);
const region = opt("region", cfg.region);
const findings = flag("with-findings")
  ? JSON.parse(fs.readFileSync(path.join(root, "config/findings.json"), "utf8"))
  : { endpoints: [], rules: [] };

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const write = (rel, content) => {
  const p = path.join(root, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
};

// Clean previously generated services so --limit shrinks cleanly.
fs.rmSync(path.join(root, "services"), { recursive: true, force: true });

const ACTIONS = [
  { action: "list",   method: "GET",    item: false, role: "viewer", crud: "list" },
  { action: "get",    method: "GET",    item: true,  role: "viewer", crud: "get" },
  { action: "create", method: "POST",   item: false, role: "write",  crud: "create" },
  { action: "update", method: "PATCH",  item: true,  role: "write",  crud: "update" },
  { action: "delete", method: "DELETE", item: true,  role: "admin",  crud: "remove" },
];

const manifest = [];
const ruleBlocks = [];
const indexes = [];
const codebases = [];
const appliedFindings = [];

for (const d of cfg.domains) {
  const resources = d.resources.slice(0, limit);
  const reserved = resources.find((r) => r === "tasks" || r === "index");
  if (reserved) throw new Error(`"${reserved}" is reserved (per-domain tasks module) in domain ${d.name}`);
  const svc = `services/${d.name}`;
  codebases.push(d.name);

  for (const r of resources) {
    let access = d.access[r] ?? d.defaultAccess;
    const rf = findings.rules.find((f) => f.resource === r);
    if (rf) { access = rf.access; appliedFindings.push({ ...rf, kind: "rule" }); }
    const owned = access === "owner";
    ruleBlocks.push(rulesFor(r, access, rf));
    indexes.push({
      collectionGroup: r, queryScope: "COLLECTION",
      fields: [{ fieldPath: "status", order: "ASCENDING" }, { fieldPath: "createdAt", order: "DESCENDING" }],
    });

    const lines = [
      `// GENERATED by scripts/generate.mjs — do not edit by hand.`,
      `import { crud, httpEndpoint, onCreatedCounter, onUpdatedAudit } from "@mock/shared";`,
      ``,
      `const R = "${r}";`,
    ];
    for (const a of ACTIONS) {
      const ef = findings.endpoints.find((f) => f.resource === r && f.action === a.action);
      const o = ef?.override ?? {};
      if (ef) appliedFindings.push({ ...ef, kind: "endpoint" });
      const minRole = a.role === "write" ? d.writeRole : a.role;
      const spec = { method: a.method, auth: o.auth ?? "member", ...(o.auth === "public" ? {} : { minRole }) };
      if (o.tenantCheck === false) spec.tenantCheck = false;
      const crudOpts = {};
      if (owned && (a.crud === "create" || a.crud === "update")) crudOpts.owned = true;
      if (o.massAssignment) crudOpts.massAssignment = true;
      const optsArg = Object.keys(crudOpts).length ? `, ${JSON.stringify(crudOpts)}` : "";
      const exportName = a.action === "delete" ? "remove" : a.action;
      lines.push(
        ef ? `// ⚠️ ${ef.id} ${ef.title}: ${ef.description}` : "",
        `export const ${exportName} = httpEndpoint(${JSON.stringify(spec)}, crud.${a.crud}(R${optsArg}));`,
      );
      const functionId = `${d.name}-${r}-${exportName}`;
      const apiPath = `/v1/${d.name}/${kebab(r)}${a.item ? "/{id}" : ""}`;
      manifest.push({
        functionId, codebase: d.name, type: "https", method: a.method, path: apiPath,
        resource: r, action: a.action, auth: spec.auth, minRole: spec.minRole ?? null,
        clientAccess: access, finding: ef?.id ?? null,
      });
    }
    lines.push(
      ``,
      `export const onCreated = onCreatedCounter(R);`,
      `export const onUpdated = onUpdatedAudit(R);`,
      ``,
    );
    for (const t of ["onCreated", "onUpdated"]) {
      manifest.push({
        functionId: `${d.name}-${r}-${t}`, codebase: d.name, type: "firestore",
        event: t === "onCreated" ? "document.created" : "document.updated",
        document: `tenants/{tenantId}/${r}/{docId}`, resource: r,
      });
    }
    write(`${svc}/src/${r}.ts`, lines.filter((l, i, arr) => !(l === "" && arr[i - 1] === "")).join("\n"));
  }

  // Per-domain jobs: callables, a schedule, and a Pub/Sub consumer.
  write(`${svc}/src/tasks.ts`, `// GENERATED by scripts/generate.mjs — do not edit by hand.
import { HttpsError, onCall } from "firebase-functions/v2/https";
import { onSchedule } from "firebase-functions/v2/scheduler";
import { onMessagePublished } from "firebase-functions/v2/pubsub";
import { logger } from "firebase-functions";
import { db } from "@mock/shared";

const DOMAIN = "${d.name}";
const RESOURCES = ${JSON.stringify(resources)};

const tenantOf = (auth: { token: Record<string, unknown> } | undefined) => {
  const t = auth?.token.tenantId;
  if (!t) throw new HttpsError("unauthenticated", "tenant claim required");
  return String(t);
};

/** Callable: the web app invokes these with httpsCallable(), not fetch(). */
export const summary = onCall(async (req) => {
  const tenantId = tenantOf(req.auth);
  const snaps = await db.getAll(...RESOURCES.map((r) => db.doc(\`tenants/\${tenantId}/_stats/\${r}\`)));
  return Object.fromEntries(snaps.map((s, i) => [RESOURCES[i], s.get("count") ?? 0]));
});

export const ping = onCall(async (req) => ({ domain: DOMAIN, uid: req.auth?.uid ?? null }));

export const requestExport = onCall(async (req) => {
  const tenantId = tenantOf(req.auth);
  const ref = await db.collection(\`tenants/\${tenantId}/_exports\`).add({ domain: DOMAIN, requestedBy: req.auth!.uid, status: "queued" });
  // In production you'd publish to the "\${DOMAIN}-exports" topic here.
  return { exportId: ref.id };
});

export const nightly = onSchedule("every day 03:00", async () => {
  logger.info(\`\${DOMAIN} nightly maintenance\`);
});

export const onExport = onMessagePublished("${d.name}-exports", async (event) => {
  logger.info(\`\${DOMAIN} export message\`, event.data.message.json);
});
`);
  for (const [n, type] of [["summary", "callable"], ["ping", "callable"], ["requestExport", "callable"], ["nightly", "scheduled"], ["onExport", "pubsub"]]) {
    manifest.push({ functionId: `${d.name}-tasks-${n}`, codebase: d.name, type });
  }

  write(`${svc}/src/index.ts`, `// GENERATED by scripts/generate.mjs — do not edit by hand.
import { setGlobalOptions } from "firebase-functions/v2";
${resources.map((r) => `import * as $${r} from "./${r}";`).join("\n")}
import * as $tasks from "./tasks";

setGlobalOptions({ region: "${region}", maxInstances: 10, memory: "256MiB" });

// Nested export => function IDs like "${d.name}-${resources[0]}-list".
export const ${d.name} = { ${[...resources, "tasks"].map((r) => `${r}: $${r}`).join(", ")} };
`);

  write(`${svc}/package.json`, JSON.stringify({
    name: `@mock/svc-${d.name}`, version: "0.0.0", private: true,
    scripts: { build: "node ../../scripts/build-service.mjs", typecheck: "tsc -p ." },
    dependencies: { "firebase-admin": "^14.5.0", "firebase-functions": "^7.4.0" },
    devDependencies: { "@mock/shared": "workspace:*", "@types/express": "^5.0.6", typescript: "^5.9.3" },
  }, null, 2) + "\n");
  write(`${svc}/tsconfig.json`, `{ "extends": "../../tsconfig.base.json", "include": ["src"] }\n`);
}

// ---------- firestore.rules ----------
function rulesFor(r, access, finding) {
  const m = `    match /${r}/{docId} {`;
  const note = finding ? `      // ⚠️ ${finding.id} ${finding.title}: ${finding.description}\n` : "";
  const body = {
    "public-read": `      allow read: if true;\n      allow write: if false;`,
    "member-read": `      allow read: if isMember(tenantId);\n      allow write: if false;`,
    "member-write": `      allow read: if isMember(tenantId);
      allow create: if hasRole(tenantId, ['editor', 'admin']) && stampsTenant(tenantId);
      allow update: if hasRole(tenantId, ['editor', 'admin']) && tenantUnchanged();
      allow delete: if hasRole(tenantId, ['admin']);`,
    "owner": `      allow read, delete: if isMember(tenantId) && resource.data.ownerUid == request.auth.uid;
      allow create: if isMember(tenantId) && stampsTenant(tenantId)
                    && request.resource.data.ownerUid == request.auth.uid;
      allow update: if isMember(tenantId) && resource.data.ownerUid == request.auth.uid
                    && request.resource.data.ownerUid == request.auth.uid && tenantUnchanged();`,
    "server-only": `      allow read, write: if false;`,
  }[access];
  if (!body) throw new Error(`unknown access level ${access} for ${r}`);
  return `${m}  // ${access}\n${note}${body}\n    }`;
}

write("firestore.rules", `rules_version = '2';
// GENERATED by scripts/generate.mjs from config/domains.json — do not edit by hand.
// These rules govern ONLY client SDK traffic (apps/web). Cloud Functions use the
// Admin SDK, which bypasses rules entirely.
service cloud.firestore {
  match /databases/{database}/documents {

    function signedIn() { return request.auth != null; }
    function isMember(tenantId) { return signedIn() && request.auth.token.tenantId == tenantId; }
    function hasRole(tenantId, roles) { return isMember(tenantId) && request.auth.token.role in roles; }
    function stampsTenant(tenantId) { return request.resource.data.tenantId == tenantId; }
    function tenantUnchanged() { return request.resource.data.tenantId == resource.data.tenantId; }

    match /users/{uid} {
      allow read: if signedIn() && request.auth.uid == uid;
      allow update: if signedIn() && request.auth.uid == uid
                    && !request.resource.data.diff(resource.data).affectedKeys().hasAny(['role', 'tenantId']);
    }

    match /tenants/{tenantId} {
      allow read: if isMember(tenantId);

${ruleBlocks.join("\n\n")}

      // Function-owned bookkeeping.
      match /{internal}/{docId} {
        allow read: if internal == '_stats' && isMember(tenantId);
      }
    }
  }
}
`);

write("firestore.indexes.json", JSON.stringify({ indexes, fieldOverrides: [] }, null, 2) + "\n");

// ---------- firebase.json ----------
write("firebase.json", JSON.stringify({
  firestore: { rules: "firestore.rules", indexes: "firestore.indexes.json" },
  functions: codebases.map((c) => ({
    source: `services/${c}/dist`,
    codebase: c,
    runtime: "nodejs22",
    predeploy: [`pnpm --dir "$PROJECT_DIR" --filter @mock/svc-${c} build`],
  })),
  hosting: { public: "apps/web/dist", ignore: ["**/.*"], rewrites: [{ source: "**", destination: "/index.html" }] },
  emulators: {
    auth: { port: 9099 }, functions: { port: 5001 }, firestore: { port: 8080 },
    pubsub: { port: 8085 }, hosting: { port: 5050 }, ui: { enabled: true, port: 4000 }, singleProjectMode: true,
  },
}, null, 2) + "\n");

// ---------- OpenAPI ----------
const http = manifest.filter((m) => m.type === "https");
const byPath = {};
for (const e of http) (byPath[e.path] ??= []).push(e);

const opId = (e) => e.functionId.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const idParam2 = { name: "id", in: "path", required: true, type: "string" };
const idParam3 = { name: "id", in: "path", required: true, schema: { type: "string" } };

// OpenAPI 3.0 — for scanners, docs, contract tests.
const oas3 = {
  openapi: "3.0.3",
  info: { title: "API Mock Monorepo", version: "1.0.0", description: "Generated from config/domains.json" },
  servers: [{ url: `https://API_GATEWAY_HOST` }, { url: "http://localhost:8787", description: "tests/api/dev-gateway.mjs" }],
  components: {
    securitySchemes: { firebase: { type: "http", scheme: "bearer", bearerFormat: "Firebase ID token (JWT)" } },
    schemas: { Doc: { type: "object", additionalProperties: true, properties: { id: { type: "string" }, status: { type: "string" } } },
               Error: { type: "object", properties: { error: { type: "string" } } } },
  },
  paths: {},
};
// Swagger 2.0 with x-google-backend — what `gcloud api-gateway api-configs create` consumes.
const gw = {
  swagger: "2.0",
  info: { title: "api-mock-gateway", version: "1.0.0" },
  schemes: ["https"], produces: ["application/json"],
  securityDefinitions: {
    firebase: {
      authorizationUrl: "", flow: "implicit", type: "oauth2",
      "x-google-issuer": `https://securetoken.google.com/${project}`,
      "x-google-jwks_uri": "https://www.googleapis.com/service_accounts/v1/metadata/x509/securetoken@system.gserviceaccount.com",
      "x-google-audiences": project,
    },
  },
  paths: {},
};

for (const [p, ops] of Object.entries(byPath)) {
  oas3.paths[p] = {}; gw.paths[p] = {};
  for (const e of ops) {
    const m = e.method.toLowerCase();
    const secured = e.auth !== "public";
    const hasBody = e.method === "POST" || e.method === "PATCH";
    oas3.paths[p][m] = {
      operationId: opId(e), tags: [e.codebase],
      summary: `${e.action} ${e.resource}`,
      "x-function-id": e.functionId, "x-min-role": e.minRole,
      ...(secured ? { security: [{ firebase: [] }] } : { security: [] }),
      parameters: [
        ...(p.includes("{id}") ? [idParam3] : []),
        { name: "tenantId", in: "query", required: false, schema: { type: "string" } },
        ...(e.action === "list" ? [{ name: "status", in: "query", schema: { type: "string" } }, { name: "limit", in: "query", schema: { type: "integer", maximum: 100 } }] : []),
      ],
      ...(hasBody ? { requestBody: { required: true, content: { "application/json": { schema: { $ref: "#/components/schemas/Doc" } } } } } : {}),
      responses: {
        [e.method === "POST" ? "201" : "200"]: { description: "OK", content: { "application/json": { schema: { $ref: "#/components/schemas/Doc" } } } },
        401: { description: "Unauthenticated" }, 403: { description: "Forbidden" }, 404: { description: "Not found" },
      },
    };
    gw.paths[p][m] = {
      operationId: opId(e),
      ...(secured ? { security: [{ firebase: [] }] } : {}),
      parameters: [...(p.includes("{id}") ? [idParam2] : []), ...(hasBody ? [{ name: "body", in: "body", schema: { type: "object" } }] : [])],
      "x-google-backend": { address: `https://${region}-${project}.cloudfunctions.net/${e.functionId}` },
      responses: { 200: { description: "OK" } },
    };
  }
}
write("openapi/openapi.json", JSON.stringify(oas3, null, 2) + "\n");
write("openapi/gateway.swagger.json", JSON.stringify(gw, null, 2) + "\n");

write("manifest/functions.json", JSON.stringify({ project, region, generatedAt: new Date().toISOString(), functions: manifest }, null, 2) + "\n");
write("manifest/findings.json", JSON.stringify(appliedFindings, null, 2) + "\n");

const counts = manifest.reduce((a, m) => ((a[m.type] = (a[m.type] ?? 0) + 1), a), {});
console.log(`Generated ${manifest.length} functions across ${codebases.length} codebases`, counts);
console.log(`${Object.keys(byPath).length} API paths, ${http.length} operations, ${appliedFindings.length} findings applied`);
